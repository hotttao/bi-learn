"""S2 source initialization, read-only queries, and independent reconciliation.

Requires access to Docker. No host-side database driver dependency.
"""

import argparse
from collections import defaultdict
from decimal import Decimal
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
COMPOSE = ["docker-compose", "-f", str(ROOT / "compose.yaml"), "--profile", "sources"]


def credentials():
    values = {}
    for line in (ROOT / ".env").read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def redact(message):
    for value in credentials().values():
        if value:
            message = message.replace(value, "[REDACTED]")
    return message


def run(args, text=None):
    return subprocess.run(
        args, input=text, text=True, capture_output=True, cwd=ROOT, encoding="utf-8"
    )


def query(source, statement, role="reader", expect_error=None):
    if source == "mysql":
        service = "mysql-source"
        auth = (
            'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysql --protocol=socket -uroot'
            if role == "admin"
            else 'MYSQL_PWD="$MYSQL_READER_PASSWORD" exec mysql --protocol=TCP -hmysql-source -ubi_reader'
        )
        command = auth + " --default-character-set=utf8mb4 --batch --raw --skip-column-names sales"
    else:
        service = "crm-source"
        auth = (
            'PGPASSWORD="$POSTGRES_PASSWORD" PGCLIENTENCODING=UTF8 exec psql -h127.0.0.1 -Ucrm_owner'
            if role == "admin"
            else 'PGPASSWORD="$CRM_READER_PASSWORD" PGCLIENTENCODING=UTF8 exec psql -hcrm-source -Ucrm_reader'
        )
        command = auth + " -dcrm -X -A -t -F '\t' -v ON_ERROR_STOP=1 -v VERBOSITY=verbose"
    result = run(COMPOSE + ["exec", "-T", service, "sh", "-c", command], statement)
    if expect_error is not None:
        if result.returncode == 0 or not re.search(expect_error, result.stderr):
            raise RuntimeError(f"{source} expected rejection {expect_error}: " + redact(result.stderr))
        return "rejected"
    if result.returncode:
        raise RuntimeError(f"{source} query failed: " + redact(result.stderr))
    return result.stdout.strip()


def seed():
    values = credentials()
    for key in ("MYSQL_SOURCE_READER_PASSWORD", "CRM_READER_PASSWORD"):
        if not re.fullmatch(r"[0-9a-f]{64}", values.get(key, "")):
            raise ValueError(f"{key} must be generated by prepare_env.py")
    for source, folder in (("mysql", "mysql"), ("crm", "postgres")):
        for name in ("001_schema.sql", "002_seed.sql"):
            query(source, (ROOT / "sql" / folder / name).read_text(), "admin")
    mysql_password = values["MYSQL_SOURCE_READER_PASSWORD"]
    query("mysql", f"""
CREATE USER IF NOT EXISTS 'bi_reader'@'%' IDENTIFIED BY '{mysql_password}';
ALTER USER 'bi_reader'@'%' IDENTIFIED BY '{mysql_password}';
GRANT SELECT ON sales.orders TO 'bi_reader'@'%';
GRANT SELECT ON sales.refunds TO 'bi_reader'@'%';
""", "admin")
    crm_password = values["CRM_READER_PASSWORD"]
    query("crm", f"""
DO $role$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'crm_reader') THEN
        CREATE ROLE crm_reader LOGIN;
    END IF;
END $role$;
ALTER ROLE crm_reader PASSWORD '{crm_password}';
ALTER ROLE crm_reader SET default_transaction_read_only = on;
REVOKE ALL ON DATABASE crm FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE crm TO crm_reader;
GRANT USAGE ON SCHEMA public TO crm_reader;
GRANT SELECT ON public.customers TO crm_reader;
""", "admin")
    print("Seed applied; existing baseline IDs preserved; readers configured.")


def rows(source, statement):
    output = query(source, statement)
    return [line.split("\t") for line in output.splitlines()] if output else []


def check(condition, message):
    if not condition:
        raise AssertionError(message)


def verify():
    # Read raw records, independently compute using Decimal, then check SQL results.
    orders = rows("mysql", "SELECT order_id,dept_id,customer_id,order_date,paid_amount FROM orders ORDER BY order_id;")
    refunds = rows("mysql", "SELECT refund_id,dept_id,order_id,refund_date,refund_amount FROM refunds ORDER BY refund_id;")
    customers = rows("crm", "SELECT dept_id,customer_id,industry FROM customers ORDER BY dept_id,customer_id;")
    customer_map = {(d, c): industry for d, c, industry in customers}
    check(len(customer_map) == len(customers), "Duplicate composite customer keys")
    order_map = {(d, oid): Decimal(paid) for oid, d, _, _, paid in orders}
    check(len({o[0] for o in orders}) == len(orders), "Duplicate global order IDs")
    refund_map = defaultdict(Decimal)
    for _, dept, oid, _, amount in refunds:
        check((dept, oid) in order_map, "Orphan or wrong-department refund")
        check(Decimal(amount) >= 0, "Negative refund")
        refund_map[dept, oid] += Decimal(amount)
    by_order, by_department, by_industry, by_day = {}, defaultdict(Decimal), defaultdict(Decimal), defaultdict(Decimal)
    for oid, dept, customer, day, amount in orders:
        paid = Decimal(amount)
        check(paid >= 0 and refund_map[dept, oid] <= paid, "Negative payment or excess cumulative refund")
        # S2 baseline requires complete CRM references; edge unknown-customer policy is S4.
        check((dept, customer) in customer_map, "Missing baseline customer")
        net = paid - refund_map[dept, oid]
        by_order[oid] = net
        by_department[dept] += net
        by_industry[customer_map[dept, customer]] += net
        by_day[day] += net
    money = lambda value: format(value, ".2f")
    summary = {
        "counts": {"orders": len(orders), "refunds": len(refunds), "customers": len(customers)},
        "paid": money(sum((Decimal(o[4]) for o in orders), Decimal(0))),
        "refund": money(sum(refund_map.values(), Decimal(0))),
        "net": money(sum(by_order.values(), Decimal(0))),
        **{key: {k: money(v) for k, v in group.items()} for key, group in (
            ("by_order", by_order), ("by_department", by_department),
            ("by_industry", by_industry), ("by_day", by_day)
        )},
    }
    expected = json.loads((ROOT / "fixtures/expected-baseline.json").read_text())
    check(summary == expected, "Baseline differs from independent expected answer: " + json.dumps(summary, ensure_ascii=False))
    sql_rows = rows("mysql", (ROOT / "sql/mysql/order_net.sql").read_text())
    check(len(sql_rows) == len(orders), "SQL changed order grain")
    check({r[0]: Decimal(r[6]) for r in sql_rows} == by_order, "SQL per-order net differs from raw-record calculation")
    checks = {}
    for name, source, statement, pattern in (
        ("mysql_reader_write", "mysql", "UPDATE orders SET paid_amount=paid_amount WHERE 1=0;", r"ERROR 1142"),
        ("mysql_reader_ddl", "mysql", "CREATE TEMPORARY TABLE s2_probe(id INT);", r"ERROR (1044|1142)"),
        ("crm_reader_write", "crm", "SET default_transaction_read_only=off; UPDATE customers SET industry=industry WHERE false;", r"42501"),
        ("crm_reader_ddl", "crm", "SET default_transaction_read_only=off; BEGIN; CREATE TABLE public.s2_probe(id INT); ROLLBACK;", r"42501"),
    ):
        checks[name] = query(source, statement, expect_error=pattern)
    for name, source, statement, pattern in (
        ("mysql_wrong_department_refund", "mysql", "START TRANSACTION; INSERT INTO refunds VALUES(999,'B',1,'2026-10-03',1); ROLLBACK;", r"ERROR 1452"),
        ("mysql_negative_payment", "mysql", "START TRANSACTION; INSERT INTO orders VALUES(999,'A',1,'2026-10-01',-1); ROLLBACK;", r"ERROR 3819"),
        ("crm_duplicate_customer", "crm", "BEGIN; INSERT INTO customers VALUES('A',1,'重复'); ROLLBACK;", r"23505"),
    ):
        checks[name] = query(source, statement, "admin", expect_error=pattern)
    snapshot = json.dumps([orders, refunds, customers], ensure_ascii=False, separators=(",", ":"))
    print(json.dumps({
        "summary": summary,
        "snapshot_sha256": hashlib.sha256(snapshot.encode()).hexdigest(),
        "checks": checks,
        "scope": "S2 raw-source reconciliation; cross-database SQL and department isolation NOT tested",
    }, ensure_ascii=False, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["seed", "verify", "query"])
    parser.add_argument("--source", choices=["mysql", "crm"], default="mysql")
    parser.add_argument("--role", choices=["reader", "admin"], default="reader")
    args = parser.parse_args()
    if args.action == "seed":
        seed()
    elif args.action == "verify":
        verify()
    else:
        print(query(args.source, sys.stdin.read(), args.role))


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, ValueError, AssertionError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
